/**
 * Regenerates everything derived from games/*: run it after adding or changing a game.
 *
 *   npm run sync
 *
 * Writes:
 *   eas.json                               build + submit profiles per game (env GAME=<id>)
 *   games/<id>/store/store.config.json     App Store listing for `eas metadata:push`
 *   games/<id>/store/play/en-US/*.txt      Google Play listing (fastlane `supply` layout), with
 *                                          changelogs/default.txt from store/releases.json
 *   games/<id>/store/RATING-NOTES.md       answers for the age-rating and data-safety forms,
 *                                          plus the console steps no tool can do
 *
 * Apple's promotional text comes from game.json `store.promotionalText`; release notes from
 * games/<id>/store/releases.json `releaseNotes[<app.version>]` (Apple gets them only once the game has
 * an earlier Apple submission there: a first version has no "What's New"). The App Review notes are
 * games/<id>/store/REVIEW-NOTES.md, written by hand and pasted into App Store Connect.
 *
 * A game that sells random items (meta.chestsForSale) gets the disclosure line at the top of
 * both store descriptions (research/policy.md checklist 1).
 */
import fs from 'node:fs';
import path from 'node:path';
import { GameConfigSchema, type GameConfig } from '../src/config/schema';
import { promotionalTextOf, type ReleasesFile } from './lib/fingerprint';

const games = require('./lib/games.js');
const build: Record<string, unknown> = {
  base: { node: '22.23.5', env: {} },
};
const submit: Record<string, unknown> = {};

/** The wording the UK ASA and the rating boards use for paid random items. */
export const RANDOM_ITEMS_LINE = 'In-game purchases (includes random items)';

function description(g: GameConfig): string {
  if (!g.meta.chestsForSale) return g.store.description;
  const text = `${RANDOM_ITEMS_LINE}\n\n${g.store.description}`;
  if (text.length > 4000) console.log(`  warn: ${g.id} description is over 4000 characters with the disclosure line; shorten it`);
  return text.slice(0, 4000);
}

const yes = (b: boolean) => (b ? 'Yes' : 'No');

/** games/<id>/store/releases.json, or an empty log. */
export function releasesOf(id: string): ReleasesFile {
  const f = path.join(games.gameDir(id), 'store', 'releases.json');
  return fs.existsSync(f) ? (JSON.parse(fs.readFileSync(f, 'utf8')) as ReleasesFile) : {};
}

/**
 * A merge game's gift boxes (game.json merge.gift, opaque to the shared schema): earned one every
 * `every` filled tickets, `slots` slots each; null for every other mode. The merge mode has no
 * daily reward and draws a cast of cartoon animals in code (no `cast` block).
 */
function mergeGift(g: GameConfig): { every: number; slots: number; lanternSlots: { n: number; slots: number } | null } | null {
  if (g.mode !== 'merge') return null;
  type Lantern = { n?: unknown; effect?: { type?: unknown; value?: unknown } };
  const m = (g as unknown as { merge?: { gift?: { every?: unknown; slots?: unknown }; lanterns?: unknown } }).merge ?? {};
  const gift = m.gift ?? {};
  // A lantern whose effect raises the slot count (decision M5: lantern 14 gives a fourth slot).
  const lanterns = (Array.isArray(m.lanterns) ? m.lanterns : []) as Lantern[];
  const more = lanterns.find((l) => l.effect?.type === 'giftSlots');
  return {
    every: Number(gift.every ?? 0),
    slots: Number(gift.slots ?? 0),
    lanternSlots: more ? { n: Number(more.n), slots: Number(more.effect?.value) } : null,
  };
}

