const bounds = (id: string, fallback: Bounds): Bounds => {
  const m = MEASURED[id];
  return m ? B(m[0], m[1], m[2], m[3]) : fallback;
};

/**
 * One entry. `k` bakes it small (k of its size: the drawing is scaled by k, its bounds measured so, its
 * slots scaled) and sets drawScale 1/k, so the world draws it at true size from fewer pixels: statics
 * away from the hero frame are baked at 0.75, the yard's edges and the lane at 0.6 or 0.5 (the budget,
 * section 6.2; the sum is in notes/art-plant.md).
 */
function entry(
  id: string,
  group: string,
  sheet: Sheet,
  footprint: [number, number],
  fallback: Bounds,
  frames: readonly string[],
  draw: Draw,
  extra: Partial<ManifestEntry> & { k?: number } = {},
): ManifestEntry {
  const { k = 1, ...rest } = extra;
  const scaled: Draw =
    k === 1
      ? draw
      : (c, v, f, h) => {
          c.save();
          c.scale(k, k);
          draw(c, v, f, h);
          c.restore();
        };
  const slots = rest.slots && k !== 1 ? Object.fromEntries(Object.entries(rest.slots).map(([n, b]) => [n, B(b.x * k, b.y * k, b.w * k, b.h * k)])) : rest.slots;
  return {
    id,
    group,
    sheet,
    footprint: { w: footprint[0], d: footprint[1] },
    bounds: bounds(id, k === 1 ? fallback : B(fallback.x * k, fallback.y * k, fallback.w * k, fallback.h * k)),
    frames,
    headings: 1,
    draw: scaled,
    ...rest,
    ...(slots ? { slots } : {}),
    ...(k !== 1 ? { drawScale: (rest.drawScale ?? 1) / k } : {}),
  };
}

