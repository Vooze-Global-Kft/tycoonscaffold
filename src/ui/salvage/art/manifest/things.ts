/**
 * The frame a thing shows when `off` of its `total` pieces have come off (0: whole). The last stage stays
 * until the last piece is off; then the world draws nothing (the waste went to the rubble skip).
 */
export function stageOf(frames: number, off: number, total: number): number {
  if (off <= 0 || total <= 0) return 0;
  if (frames <= 1) return 0;
  return Math.min(frames - 1, Math.max(1, Math.ceil((off / total) * (frames - 1))));
}

