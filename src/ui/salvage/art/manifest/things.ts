/** The sizes a piece is seen at: on the ground (true size, its shadow), carried (0.8, no shadow), in a bay heap (0.6). */
export const PIECE_SIZES = { ground: 1, carried: 0.8, bay: 0.6 } as const;

function pieceDraw(kind: string, metres: number, size: keyof typeof PIECE_SIZES): Draw {
  return (c, v) => {
    const s = metres * v.ppm * PIECE_SIZES[size];
    if (size === 'ground') {
      groundShadow(c, v, metres * 0.45, metres * 0.22, 0, 0, 0.12);
      at(c, 0, -0.06 * v.ppm * v.lift, () => pieceGlyph(c, kind, 0, 0, s, 0, 2));
    } else pieceGlyph(c, kind, 0, 0, s, 0, size === 'bay' ? 5 : 3);
  };
}

