/**
 * One entry. `k` bakes it small (the drawing scaled by k, its bounds measured so) and sets drawScale 1/k,
 * so the world draws it at true size from fewer pixels (the budget, yard-stage1.md 6.2): the hero frame's
 * things at 1, the old stock at 0.6, the big steel at 0.45.
 */
function entry(id: string, group: string, footprint: [number, number], fallback: Bounds, frames: readonly string[], draw: Draw, k = 1): ManifestEntry {
  const scaled: Draw =
    k === 1
      ? draw
      : (c, v, f, h) => {
          c.save();
          c.scale(k, k);
          draw(c, v, f, h);
          c.restore();
        };
  const m = MEASURED[id];
  return {
    id,
    group,
    sheet: 'A',
    footprint: { w: footprint[0], d: footprint[1] },
    bounds: m ? B(m[0], m[1], m[2], m[3]) : B(fallback.x * k, fallback.y * k, fallback.w * k, fallback.h * k),
    frames,
    headings: 1,
    draw: scaled,
    ...(k !== 1 ? { drawScale: 1 / k } : {}),
  };
}

