/** Pixels of this part at a density (cells of every frame), for the budget. */
export function thingsPixels(density: number): number {
  let n = 0;
  for (const e of THINGS) n += Math.ceil(e.bounds.w * density) * Math.ceil(e.bounds.h * density) * e.frames.length;
  return n;
}
