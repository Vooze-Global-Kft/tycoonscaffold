import { it } from 'vitest';
import { FIXTURE_NOW, SALVAGE_TEST } from '../fixtures/salvage';
import * as R from '../salvage';
import * as T from './rate';
it('dbg', () => {
  const cfg = { mode: 'salvage', salvage: SALVAGE_TEST } as any;
  let g = R.createSalvage(cfg, { cash: 100000, lifetimeEarnings: 0, lastSavedAt: FIXTURE_NOW, stats: { playSeconds: 0, clockHigh: FIXTURE_NOW } } as any, FIXTURE_NOW);
  for (const item of ['sack', 'sledge', 'trolley', 'truck', 'stripper', 'bench', 'crucible']) g = R.buy(cfg, g, item, R.shopPrice(cfg, g, item) ?? 0, g.salvage.t);
  g = R.hire(cfg, g, 'hand', 100, g.salvage.t);
  g = R.hire(cfg, g, 'cutter', 300, g.salvage.t);
  g = R.hire(cfg, g, 'driver', 500, g.salvage.t);
  g = R.jump(cfg, g, 600);
  const e2: any[] = [];
  let t0 = performance.now();
  const g1 = R.jump(cfg, g, 600 + 14400, e2);
  const ms = performance.now() - t0;
  t0 = performance.now();
  for (let i = 0; i < 2000; i++) T.checks({ cfg, c: cfg.salvage, s: g1.salvage, cash: g1.cash, earned: 0, ev: [], live: false, ms0: g1.salvage.clock.highMs, t0: g1.salvage.t, away: null } as any, g1.salvage.t);
  const chk = (performance.now() - t0) / 2000;
  process.stderr.write(JSON.stringify({ ms, events: e2.length, chk, things: g1.salvage.things.length, pieces: g1.salvage.pieces.length, cash: g1.cash, tickets: g1.salvage.tickets.length }) + '\n');
});
